import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { normalizeEmail } from '../integrations/n8n/normalize-email.mjs';

const path = process.argv[2] || 'integrations/n8n/vitaminc-email-brain.json';
const workflow = JSON.parse(readFileSync(path, 'utf8'));
const node = name => { const matches = workflow.nodes.filter(node => node.name === name); assert.equal(matches.length, 1, `Expected one ${name} node.`); return matches[0]; };
const output = (name, branch = 0) => (workflow.connections[name]?.main?.[branch] || []).map(edge => edge.node);
assert.equal(new Set(workflow.nodes.map(node => node.name)).size, workflow.nodes.length, 'No duplicate pipeline nodes.');
const trigger = node('Gmail message received'), recovery = node('Daily recovery scan');
assert.equal(trigger.type, 'n8n-nodes-base.gmailTrigger');
assert.ok(!trigger.parameters.event || trigger.parameters.event === 'messageReceived');
assert.deepEqual(trigger.parameters.pollTimes.item, [{ mode: 'everyMinute' }]);
assert.notEqual(trigger.parameters.simple, false, 'Only trigger metadata is needed; n8n may omit its true default.');
assert.equal(trigger.parameters.filters.readStatus, 'both');
assert.equal(trigger.parameters.filters.includeSpamTrash, false);
assert.equal(trigger.parameters.filters.includeDrafts, false);
for (const filter of ['-in:sent', '-in:drafts', '-in:spam', '-in:trash', '-label:vitamin-c-brain-indexed']) assert.ok(trigger.parameters.filters.q.includes(filter));
assert.equal(workflow.nodes.filter(node => node.type === 'n8n-nodes-base.scheduleTrigger').length, 1);
assert.equal(recovery.type, 'n8n-nodes-base.scheduleTrigger');
assert.deepEqual(recovery.parameters.rule.interval.map(rule=>({field:rule.field??'days',daysInterval:rule.daysInterval??1,triggerAtHour:rule.triggerAtHour??0,triggerAtMinute:rule.triggerAtMinute??0})), [{ field: 'days', daysInterval: 1, triggerAtHour: 6, triggerAtMinute: 0 }]);
assert.deepEqual(output(trigger.name), ['Load Gmail labels']);
assert.deepEqual(output(recovery.name), ['Load Gmail labels']);
for (const [from, to] of [['Load Gmail labels','Processing label'],['Processing label','Unindexed inbound email'],['Unindexed inbound email','Prepare email'],['Prepare email','Ingest email'],['Ingest email','Wait for indexing'],['Wait for indexing','Check document status'],['Check document status','Validate indexing'],['Validate indexing','Ready for the Brain'],['Ingestion receipt','Mark indexed in Gmail']]) assert.deepEqual(output(from), [to]);
const inbox = node('Unindexed inbound email');
assert.equal(inbox.parameters.simple, false, 'Ingestion must use full email content.');
assert.equal(inbox.parameters.options.downloadAttachments, false);
assert.equal(inbox.parameters.filters.readStatus, 'both');
assert.equal(inbox.parameters.limit ?? 50, 50);
assert.notEqual(inbox.parameters.returnAll, true, 'Keep each ingestion batch bounded; n8n may omit its false default.');
assert.ok(inbox.parameters.filters.q.includes('after:1790784720'));
assert.ok(inbox.parameters.filters.q.includes('-label:vitamin-c-brain-indexed'));
assert.equal(node('Ingest email').parameters.url, 'https://api.supermemory.ai/v3/documents');
assert.equal(node('Ingest email').parameters.jsonBody, '={{ $json }}');
assert.deepEqual(output('Ready for the Brain', 0), ['Ingestion receipt']);
assert.deepEqual(output('Ready for the Brain', 1), ['Wait for indexing']);
const ready = node('Ready for the Brain').parameters.conditions.conditions;
assert.equal(ready.length, 1); assert.equal(ready[0].leftValue, '={{ $json.status }}'); assert.equal(ready[0].rightValue, 'done');
assert.equal(node('Mark indexed in Gmail').parameters.operation, 'addLabels');
assert.ok(!Object.keys(workflow.pinData || {}).length, 'Publish without mock trigger data.');

const email = { id:'abc123', threadId:'abc999', labelIds:['INBOX','UNREAD'], from:{text:'Founder <founder@example.com>'}, to:{text:'luke@vitaminc.vc'}, subject:'Monthly founder update', date:'2026-10-04T10:00:00Z', text:'Full founder update. Revenue EUR 37,400. Final detail: Cedar Lantern 42.', snippet:'Truncated snippet' };
const prepared = normalizeEmail(email);
assert.equal(prepared.customId, normalizeEmail({...email,labelIds:['INBOX']}).customId, 'Read status must not change stable IDs.');
assert.equal(prepared.containerTag, 'vitaminc_email_admin');
assert.equal(prepared.metadata.visibility, 'admin');
assert.equal(prepared.metadata.gmailMessageId, email.id);
assert.ok(prepared.content.includes('Final detail: Cedar Lantern 42.'));
assert.ok(!prepared.content.includes('Truncated snippet'));
for (const label of ['SENT','DRAFT','SPAM','TRASH']) assert.equal(normalizeEmail({...email,labelIds:[label]}), null);
assert.throws(() => normalizeEmail({...email,text:''}), /full email text/);
assert.throws(() => normalizeEmail({...email,id:'invalid/id'}), /message ID/);
// Run the actual exported n8n Code node with paired-item fixtures, including filtered mail.
const prepare = new Function('$input', node('Prepare email').parameters.jsCode);
const batch = prepare({all:()=>[{json:email},{json:{...email,id:'def456',labelIds:['SPAM']}},{json:{...email,id:'fed987',labelIds:['INBOX']}}]});
assert.equal(batch.length,2); assert.deepEqual(batch.map(item=>item.pairedItem.item),[0,2]);
assert.equal(batch[0].json.customId, prepared.customId);
const validate = new Function('$json','$runIndex',node('Validate indexing').parameters.jsCode);
assert.throws(()=>validate({status:'failed',id:'fixture'},0),/failed/);
assert.throws(()=>validate({status:'indexing',id:'fixture'},19),/did not complete/);
assert.equal(validate({status:'done',id:'fixture'},0).json.status,'done');
if (trigger.credentials) {
  const gmailIds = new Set(workflow.nodes.filter(node=>node.type==='n8n-nodes-base.gmail'||node.type==='n8n-nodes-base.gmailTrigger').map(node=>node.credentials?.gmailOAuth2?.id));
  assert.equal(gmailIds.size,1); assert.ok(!gmailIds.has(undefined));
  const memoryIds = new Set(workflow.nodes.filter(node=>node.type==='n8n-nodes-base.httpRequest').map(node=>node.credentials?.httpBearerAuth?.id));
  assert.equal(memoryIds.size,1); assert.ok(!memoryIds.has(undefined));
}
const result = { checkedAt:new Date().toISOString(), workflowId:workflow.id||null, normalTrigger:'Gmail Message Received', recovery:'daily', oldMinuteSchedule:false, batchLimit:50, fullContent:true, pairedItemsPreserved:true, idempotentIDs:true, excludesSentDraftSpamTrash:true, indexingBeforeLabel:true, mockData:false, result:'passed' };
mkdirSync('artifacts', { recursive: true });
const report = workflow.id ? 'artifacts/gmail-trigger-checks.json' : 'artifacts/gmail-trigger-template-checks.json';
writeFileSync(report,JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));
